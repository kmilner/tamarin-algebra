fn checked_output(command: &mut std::process::Command) -> std::process::Output {
    let output = command.output().unwrap_or_else(|error| {
        panic!(
            "could not run {command:?}: {error}; the lean-unification feature requires elan/Lake"
        )
    });
    assert!(
        output.status.success(),
        "{command:?} failed:\n{}\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    output
}

/// The declarations Lean's C backend generated for the exported functions and
/// for the module initializer, as a header.
fn generated_declarations(generated: &str) -> String {
    let mut header = String::from(
        "/* Generated by build.rs from the C that Lean emitted for TamarinRuntime. */\n\
         #include <lean/lean.h>\n",
    );
    for line in generated.lines() {
        let Some(declaration) = line.strip_prefix("LEAN_EXPORT ") else {
            continue;
        };
        let Some((head, _)) = declaration.split_once('(') else {
            continue;
        };
        let name = head.rsplit([' ', '*']).next().unwrap_or("");
        if name.starts_with("tamarin_") && declaration.ends_with(");") {
            header.push_str(declaration);
            header.push('\n');
        } else if name.starts_with("initialize_") && name.ends_with("_TamarinRuntime") {
            // Only the definition is emitted for the initializer.
            let signature = declaration.trim_end_matches('{').trim_end();
            header.push_str(signature);
            header.push_str(";\n");
        }
    }
    header
}

/// The functions `source` declares `extern`, by name.
fn extern_declarations(source: &str) -> Vec<String> {
    let mut names = Vec::new();
    for statement in source.split(';') {
        let Some(at) = statement.rfind("extern ") else {
            continue;
        };
        let Some((head, _)) = statement[at..].split_once('(') else {
            continue;
        };
        let name = head
            .trim_end()
            .rsplit([' ', '*', '\n'])
            .next()
            .unwrap_or("");
        names.push(name.to_string());
    }
    names
}

/// Rust for one C type of the bridge's public surface. Only the types listed
/// here may cross it, so a new one is a deliberate change to this table.
fn rust_type(c: &str, structs: &[String]) -> String {
    let spaced = c.replace('*', " * ");
    let words: Vec<&str> = spaced.split_whitespace().collect();
    let (constant, words) = match words.split_first() {
        Some((&"const", rest)) => (true, rest),
        _ => (false, &words[..]),
    };
    let (base, pointer) = match words {
        [base] => (*base, false),
        [base, "*"] => (*base, true),
        _ => panic!("native/lean_unification.c: unsupported type `{c}` in the bridge's interface"),
    };
    let base = match base {
        "uint8_t" => "u8".to_string(),
        "uint64_t" => "u64".to_string(),
        "size_t" => "usize".to_string(),
        "void" if pointer => "::core::ffi::c_void".to_string(),
        name if structs.iter().any(|s| s == name) => rust_struct_name(name),
        _ => panic!("native/lean_unification.c: unsupported type `{c}` in the bridge's interface"),
    };
    match (pointer, constant) {
        (false, false) => base,
        (true, true) => format!("*const {base}"),
        (true, false) => format!("*mut {base}"),
        (false, true) => {
            panic!("native/lean_unification.c: unsupported type `{c}` in the bridge's interface")
        }
    }
}

fn rust_struct_name(c: &str) -> String {
    c.split('_')
        .map(|part| {
            let mut letters = part.chars();
            letters.next().map_or(String::new(), |first| {
                first.to_ascii_uppercase().to_string() + letters.as_str()
            })
        })
        .collect()
}

/// A C declarator `type name` as (name, Rust type).
fn rust_field(c: &str, structs: &[String]) -> (String, String) {
    let c = c.trim();
    let at = c
        .rfind(|ch: char| !(ch.is_ascii_alphanumeric() || ch == '_'))
        .unwrap_or_else(|| panic!("native/lean_unification.c: unnamed declarator `{c}`"));
    (c[at + 1..].to_string(), rust_type(&c[..=at], structs))
}

/// The Rust declarations of everything the bridge defines for its caller: the
/// `typedef struct`s and every function that is not `static`. The Rust backend
/// declares none of them itself, so a call that disagrees with the C
/// definition in the number or the type of an argument or in the return type
/// does not compile.
fn rust_bindings(source: &str, lean_header: &str) -> String {
    // Comments and preprocessor lines carry no declarations.
    let mut text = String::new();
    let mut rest = source;
    while let Some(at) = rest.find("/*") {
        text.push_str(&rest[..at]);
        let end = rest[at..]
            .find("*/")
            .expect("unterminated comment in the bridge");
        rest = &rest[at + end + 2..];
    }
    text.push_str(rest);
    let text: String = text
        .lines()
        .filter(|line| !line.trim_start().starts_with('#'))
        .map(|line| line.split("//").next().unwrap())
        .collect::<Vec<_>>()
        .join("\n");

    // Top-level items: `head { body } tail ;` for a struct typedef, and
    // `head { body }` for a function definition. A statement that ends at
    // depth zero without a body is a declaration of something defined
    // elsewhere and contributes nothing.
    let mut structs: Vec<String> = Vec::new();
    let mut out =
        String::from("// Generated by build.rs from native/lean_unification.c. Do not edit.\n");
    let mut functions = String::new();
    let (mut depth, mut head, mut body) = (0usize, String::new(), String::new());
    let mut pending_struct: Option<String> = None;
    for ch in text.chars() {
        match ch {
            '{' => {
                if depth > 0 {
                    body.push(ch);
                }
                depth += 1;
            }
            '}' => {
                depth -= 1;
                if depth > 0 {
                    body.push(ch);
                    continue;
                }
                let item = head.split_whitespace().collect::<Vec<_>>().join(" ");
                head.clear();
                if item == "typedef struct" {
                    pending_struct = Some(std::mem::take(&mut body));
                    continue;
                }
                body.clear();
                if item.starts_with("static ") {
                    continue;
                }
                let (signature, parameters) = item
                    .strip_suffix(')')
                    .and_then(|item| item.split_once('('))
                    .unwrap_or_else(|| panic!("native/lean_unification.c: cannot read `{item}`"));
                let at = signature
                    .rfind(|ch: char| !(ch.is_ascii_alphanumeric() || ch == '_'))
                    .unwrap_or_else(|| panic!("native/lean_unification.c: cannot read `{item}`"));
                let (result, name) = (signature[..=at].trim(), &signature[at + 1..]);
                assert!(
                    name.starts_with("tamarin_lean_"),
                    "native/lean_unification.c defines the public function {name}: the bridge's \
                     interface is the functions named tamarin_lean_*, everything else is static"
                );
                let parameters: Vec<String> = match parameters.trim() {
                    "void" => Vec::new(),
                    list => list
                        .split(',')
                        .map(|parameter| {
                            let (name, ty) = rust_field(parameter, &structs);
                            format!("{name}: {ty}")
                        })
                        .collect(),
                };
                let result = match result {
                    "void" => String::new(),
                    other => format!(" -> {}", rust_type(other, &structs)),
                };
                functions.push_str(&format!(
                    "    pub fn {name}({}){result};\n",
                    parameters.join(", ")
                ));
            }
            ';' if depth == 0 => {
                if let Some(fields) = pending_struct.take() {
                    let name = head.trim().to_string();
                    let fields: Vec<String> = fields
                        .split(';')
                        .filter(|field| !field.trim().is_empty())
                        .map(|field| {
                            let (name, ty) = rust_field(field, &structs);
                            format!("    pub {name}: {ty},\n")
                        })
                        .collect();
                    out.push_str(&format!(
                        "#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {} {{\n{}}}\n",
                        rust_struct_name(&name),
                        fields.concat()
                    ));
                    structs.push(name);
                }
                head.clear();
            }
            _ if depth == 0 => head.push(ch),
            _ => body.push(ch),
        }
    }
    assert!(!functions.is_empty(), "the bridge defines no function");
    // A Lean export whose arguments and result are all machine words needs no
    // bridge function. Its Rust declaration comes from the declaration Lean
    // generated. Every other export takes or returns Lean objects and is
    // reachable through the bridge only.
    let scalar = |c: &str| matches!(c, "uint8_t" | "uint64_t" | "size_t");
    for line in lean_header.lines() {
        let Some((signature, parameters)) = line
            .strip_suffix(");")
            .and_then(|line| line.split_once('('))
        else {
            continue;
        };
        let Some((result, name)) = signature.rsplit_once(' ') else {
            continue;
        };
        let parameters: Vec<&str> = parameters.split(',').map(str::trim).collect();
        if !name.starts_with("tamarin_")
            || !scalar(result.trim())
            || !parameters.iter().all(|parameter| scalar(parameter))
        {
            continue;
        }
        let parameters: Vec<String> = parameters
            .iter()
            .enumerate()
            .map(|(i, parameter)| format!("a{i}: {}", rust_type(parameter, &structs)))
            .collect();
        functions.push_str(&format!(
            "    pub fn {name}({}) -> {};\n",
            parameters.join(", "),
            rust_type(result.trim(), &structs)
        ));
    }
    out.push_str("unsafe extern \"C\" {\n");
    out.push_str(&functions);
    out.push_str("}\n");
    out
}

fn main() {
    use std::path::PathBuf;
    use std::process::Command;

    let host = std::env::var("HOST").unwrap();
    let target = std::env::var("TARGET").unwrap();
    assert_eq!(
        host, target,
        "lean-unification currently supports native host builds only"
    );
    assert!(
        target == "x86_64-unknown-linux-gnu",
        "lean-unification currently supports x86_64 Linux GNU; other native link configurations are not yet validated"
    );

    let crate_dir = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").unwrap());
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
    let lake = std::env::var_os("TAMARIN_LAKE").unwrap_or_else(|| "lake".into());
    println!("cargo:rerun-if-env-changed=TAMARIN_LAKE");
    println!("cargo:rerun-if-env-changed=LEAN_CC");
    println!("cargo:rerun-if-env-changed=TAMARIN_ALGEBRA_SKIP_PROOFS");
    println!("cargo:rerun-if-changed=native/lean_unification.c");
    // Cargo git checkouts can be shared by independent target directories.
    // Give Lake a private .lake directory while preserving source identities.
    let source_dir = crate_dir.join("lean");
    let lean_dir = out_dir.join("lean");
    std::fs::create_dir_all(&lean_dir).unwrap();
    for name in [
        "lean-toolchain",
        "lakefile.toml",
        "lake-manifest.json",
        "TamarinWire.lean",
        "TamarinRuntime.lean",
        "TamarinRuntime",
        "Tamarin.lean",
        "TamarinCI.lean",
        "TamarinProposers.lean",
        "Tamarin",
        "Tests",
        "ExportManifest.txt",
        "SpecManifest.txt",
    ] {
        let source = source_dir.join(name);
        println!("cargo:rerun-if-changed={}", source.display());
        #[cfg(unix)]
        {
            let link = lean_dir.join(name);
            if std::fs::read_link(&link).ok().as_ref() != Some(&source) {
                if link.is_symlink() {
                    std::fs::remove_file(&link).unwrap();
                }
                std::os::unix::fs::symlink(&source, &link).unwrap();
            }
        }
    }
    println!("cargo::metadata=lean_dir={}", lean_dir.display());

    // The runtime is linked only after the proof root has been elaborated
    // against this exact source and the export audit has accepted the result:
    // every exported function then has its contract theorems, their statements
    // and every definition those statements depend on are the recorded ones
    // (ExportManifest.txt, SpecManifest.txt), and none of the code behind an
    // export escapes them. CI additionally replays the whole
    // environment in the kernel (`leanchecker --fresh`), which is too slow here.
    let skip_proofs = std::env::var_os("TAMARIN_ALGEBRA_SKIP_PROOFS").is_some_and(|v| v != "0");
    if skip_proofs {
        println!(
            "cargo:warning=TAMARIN_ALGEBRA_SKIP_PROOFS is set: the Lean proofs and the export \
             audit were NOT checked for this build of the algebra runtime"
        );
    } else {
        checked_output(Command::new(&lake).current_dir(&lean_dir).args([
            "build",
            "TamarinCI",
            "TamarinRuntime",
        ]));
        checked_output(Command::new(&lake).current_dir(&lean_dir).args([
            "env",
            "lean",
            "--run",
            "Tests/ExportAudit.lean",
            "--sources",
            ".",
        ]));
    }
    let archive_output = checked_output(
        Command::new(&lake)
            .current_dir(&lean_dir)
            .args(["query", "TamarinRuntime:static"]),
    );
    let archive_text = String::from_utf8(archive_output.stdout).expect("Lake output is UTF-8");
    let archive = PathBuf::from(archive_text.trim());
    assert!(
        archive.is_file(),
        "Lake did not return a native archive: {archive_text}"
    );
    let runtime_archive = out_dir.join("libtamarin_lean_runtime.a");
    std::fs::copy(archive, &runtime_archive).unwrap();

    // Lake's library archive contains only modules owned by TamarinRuntime.
    // Include precisely the imported reference modules. The proof-only CI
    // target stays outside the runtime.
    let imports = checked_output(
        Command::new(&lake)
            .current_dir(&lean_dir)
            .args(["query", "+TamarinRuntime:transImports"]),
    );
    let imports = String::from_utf8(imports.stdout).expect("Lake module names are UTF-8");
    let mut targets = Vec::new();
    for module in imports.lines().filter(|m| m.starts_with("Tamarin.")) {
        targets.push(format!("+{module}:o"));
    }
    if !targets.is_empty() {
        let objects = checked_output(
            Command::new(&lake)
                .current_dir(&lean_dir)
                .arg("query")
                .args(&targets),
        );
        let objects = String::from_utf8(objects.stdout).expect("Lake object paths are UTF-8");
        let paths: Vec<_> = objects.lines().collect();
        assert_eq!(paths.len(), targets.len(), "missing Lean reference object");
        // ar and rustc identify members by basename. For example both
        // Tamarin.ACBasis and TamarinRuntime.ACBasis compile to ACBasis.c.o.
        let mut ar = Command::new("ar");
        ar.arg("qs").arg(&runtime_archive);
        for (target, object) in targets.iter().zip(paths) {
            let module = target
                .strip_prefix('+')
                .unwrap()
                .strip_suffix(":o")
                .unwrap();
            let named = out_dir.join(format!("{module}.o"));
            std::fs::copy(object, &named).unwrap();
            ar.arg(named);
        }
        checked_output(&mut ar);
    }

    let prefix_output = checked_output(Command::new(&lake).current_dir(&lean_dir).args([
        "env",
        "lean",
        "--print-prefix",
    ]));
    let prefix = PathBuf::from(String::from_utf8(prefix_output.stdout).unwrap().trim());
    // The bridge declares the Lean exports by hand. Compile it against the
    // declarations Lean generated, so that a prototype which disagrees with
    // the compiled function is a compile error, and require that every
    // function it declares has such a generated declaration.
    let generated = checked_output(
        Command::new(&lake)
            .current_dir(&lean_dir)
            .args(["query", "+TamarinRuntime:c"]),
    );
    let generated = String::from_utf8(generated.stdout).expect("Lake output is UTF-8");
    let generated = std::fs::read_to_string(generated.trim())
        .expect("Lake did not return the generated C for TamarinRuntime");
    let header_text = generated_declarations(&generated);
    let bridge_source = std::fs::read_to_string(crate_dir.join("native/lean_unification.c"))
        .expect("the C bridge is readable");
    for name in extern_declarations(&bridge_source) {
        let lean_runtime = name.starts_with("lean_");
        assert!(
            lean_runtime
                || header_text.contains(&format!(" {name}("))
                || header_text.contains(&format!("*{name}(")),
            "native/lean_unification.c declares {name}, which Lean did not generate"
        );
    }
    // The other side of the bridge: the Rust backend takes its declarations
    // of the bridge's functions and structs from this file (src/lib.rs).
    std::fs::write(
        out_dir.join("bridge.rs"),
        rust_bindings(&bridge_source, &header_text),
    )
    .unwrap();
    let header = out_dir.join("tamarin_lean_exports.h");
    std::fs::write(&header, header_text).unwrap();
    let shim = out_dir.join("lean_unification.o");
    checked_output(
        Command::new(&lake)
            .current_dir(&lean_dir)
            .args(["env", "leanc", "-O3", "-DNDEBUG", "-c", "-include"])
            .arg(&header)
            .arg(crate_dir.join("native/lean_unification.c"))
            .arg("-o")
            .arg(&shim),
    );
    checked_output(
        Command::new("ar")
            .arg("crs")
            .arg(out_dir.join("libtamarin_lean_bridge.a"))
            .arg(shim),
    );

    // Lean and the prover each bundle mimalloc. They must not share allocator
    // globals or resolve each other's mi_* calls: versions and heap ownership
    // are independent. Namespace both definitions AND references throughout
    // the Lean-owned archives, including generated code and the C shim.
    // All copies stay in OUT_DIR; the installed toolchain remains untouched.
    let mut lean_archives = vec![
        out_dir.join("libtamarin_lean_bridge.a"),
        out_dir.join("libtamarin_lean_runtime.a"),
    ];
    for name in ["Std", "Init", "leanrt", "leancpp"] {
        let filename = format!("lib{name}.a");
        let copy = out_dir.join(&filename);
        std::fs::copy(prefix.join("lib/lean").join(filename), &copy).unwrap();
        lean_archives.push(copy);
    }
    let symbols = checked_output(
        Command::new("nm")
            .args(["-g", "--format=posix"])
            .args(&lean_archives),
    );
    let allocator_symbols: std::collections::BTreeSet<_> = std::str::from_utf8(&symbols.stdout)
        .expect("nm symbol names are UTF-8")
        .lines()
        .filter_map(|line| line.split_whitespace().next())
        .filter(|name| name.trim_start_matches('_').starts_with("mi_"))
        .collect();
    assert!(
        allocator_symbols.contains("mi_malloc"),
        "Lean allocator layout changed: review allocator isolation before linking"
    );
    let map = out_dir.join("lean_allocator_symbols.map");
    std::fs::write(
        &map,
        allocator_symbols
            .iter()
            .map(|name| format!("{name} tamarin_lean_alloc_{name}\n"))
            .collect::<String>(),
    )
    .unwrap();
    for archive in &lean_archives {
        checked_output(
            Command::new("objcopy")
                .arg(format!("--redefine-syms={}", map.display()))
                .arg(archive),
        );
    }

    println!("cargo:rustc-link-search=native={}", out_dir.display());
    println!(
        "cargo:rustc-link-search=native={}",
        prefix.join("lib/lean").display()
    );
    println!(
        "cargo:rustc-link-search=native={}",
        prefix.join("lib").display()
    );
    for library in [
        "tamarin_lean_bridge",
        "tamarin_lean_runtime",
        "Std",
        "Init",
        "leanrt",
        "leancpp",
        "cadical",
        "c++",
        "c++abi",
        "gmp",
        "uv",
        "ssl",
        "crypto",
        "unwind",
    ] {
        println!("cargo:rustc-link-lib=static={library}");
    }
    for library in ["pthread", "dl", "m", "rt"] {
        println!("cargo:rustc-link-lib=dylib={library}");
    }
}
